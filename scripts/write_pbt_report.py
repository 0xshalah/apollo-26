"""Build docs/pbt-report.md from a full-profile pytest run.

Inputs are the runner's own artifacts written by ``scripts/pbt_full.cmd``:
the text log (``--hypothesis-show-statistics``) and the JUnit XML. Every number
in the report is copied from them.

    python scripts/write_pbt_report.py --log telemetry/state/pbt-full.txt \
        --junit telemetry/state/pbt-full.xml --out docs/pbt-report.md
"""

from __future__ import annotations

import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path

_TEST = re.compile(r"^(tests/\S+?)::(\S+?):\s*$")
_PHASE = re.compile(r"^\s+- during (\w+) phase \(([\d.]+) seconds\):")
_COUNTS = re.compile(r"^\s+- (\d+) passing, (\d+) failing, and (\d+) invalid test cases")
_STOP = re.compile(r"^\s+- Stopped because (.+?)\s*$")


def parse_statistics(log: str) -> list[dict[str, object]]:
    rows: list[dict[str, object]] = []
    current: dict[str, object] | None = None
    phase = ""
    for line in log.splitlines():
        if match := _TEST.match(line):
            current = {"file": match.group(1), "test": match.group(2), "phases": {}}
            rows.append(current)
            continue
        if current is None:
            continue
        if match := _PHASE.match(line):
            phase = match.group(1)
            current["phases"][phase] = {"seconds": float(match.group(2))}  # type: ignore[index]
        elif (match := _COUNTS.match(line)) and phase:
            current["phases"][phase].update(  # type: ignore[index]
                passing=int(match.group(1)), failing=int(match.group(2)), invalid=int(match.group(3))
            )
        elif match := _STOP.match(line):
            current["stop"] = match.group(1)
    return rows


def junit_totals(path: Path) -> dict[str, float]:
    root = ET.parse(path).getroot()
    suites = [root] if root.tag == "testsuite" else list(root.iter("testsuite"))
    totals = {"tests": 0, "failures": 0, "errors": 0, "skipped": 0, "time": 0.0}
    for suite in suites:
        for key in ("tests", "failures", "errors", "skipped"):
            totals[key] += int(suite.get(key, 0))
        totals["time"] += float(suite.get("time", 0.0))
    return totals


def render(log: str, totals: dict[str, float], rows: list[dict[str, object]]) -> str:
    def first(prefix: str) -> str:
        return next((line.split("=", 1)[1].strip() for line in log.splitlines() if line.startswith(prefix)), "unknown")

    versions = next((line for line in log.splitlines() if line.startswith("python ")), "unknown")
    exit_code = first("PYTEST_EXIT=")
    passed = int(totals["tests"] - totals["failures"] - totals["errors"] - totals["skipped"])
    lines = [
        "# Property-based test report (full profile)",
        "",
        "Generated by `scripts/write_pbt_report.py` from the artifacts of `scripts/pbt_full.cmd`.",
        "Profile `full` sets Hypothesis `max_examples=10000` (`tests/conftest.py`); seed `--hypothesis-seed=2026`.",
        "Tests that pin their own `max_examples` (for example the audio-heavy modem properties) keep that value; the table shows the real count per test.",
        "",
        f"- Run started: {first('START=')}; ended: {first('END=')}",
        f"- Environment: {versions}",
        f"- pytest exit code: **{exit_code}**",
        f"- Tests: {int(totals['tests'])} total, **{passed} passed**, {int(totals['failures'])} failed, "
        f"{int(totals['errors'])} errors, {int(totals['skipped'])} skipped; JUnit time {totals['time']:.1f} s",
        "",
        "## Hypothesis statistics per property test",
        "",
        "| Test | Generate phase (s) | Passing | Failing | Invalid | Stopped because |",
        "| :-- | --: | --: | --: | --: | :-- |",
    ]
    for row in rows:
        generate = row["phases"].get("generate", {})  # type: ignore[union-attr]
        lines.append(
            f"| `{row['file']}::{row['test']}` | {generate.get('seconds', '')} | {generate.get('passing', '')} | "
            f"{generate.get('failing', '')} | {generate.get('invalid', '')} | {row.get('stop', '')} |"
        )
    lines += [
        "",
        "Non-property tests (unit, integration, end-to-end abuse scenarios) ran in the same session and are included in the totals above.",
        "The TypeScript property P9 runs separately with `npm run test:full` (fast-check, 10,000 runs per property).",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--log", type=Path, required=True)
    parser.add_argument("--junit", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args(argv)
    log = args.log.read_text(encoding="utf-8", errors="replace")
    report = render(log, junit_totals(args.junit), parse_statistics(log))
    args.out.write_text(report, encoding="utf-8")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
